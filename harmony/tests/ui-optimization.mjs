import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { fixture, wav } from './helpers.js';
const f = await fixture(), c = f.client();
await c.register('batchlistener');
const ids = [];
for (const name of ['晨光', '夜行', '专注', '晴日']) ids.push((await c.import(`${name}.wav`, wav(40))).data.track.id);
const list = (await c.request('/playlists', 'POST', {name:'通勤时光'})).data.playlist;
await c.request(`/playlists/${list.id}/tracks`, 'PUT', {version:list.version,trackIds:ids});
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1360,height:900}});
await context.addCookies([{name:'harmony_session',value:c.cookie.split('=')[1],url:f.url}]);
const page = await context.newPage(), errors=[];
page.on('pageerror', e=>errors.push(e.message));
const click = (action,id='') => page.locator(`[data-action="${action}"]${id ? `[data-id="${id}"]`:''}`).first().click();
const row = id => page.locator(`tr[data-track="${id}"]`);
async function select(id,shift=false) { await row(id).hover(); await row(id).locator('[data-select-track]').click({modifiers:shift?['Shift']:[]}); }
try {
 await mkdir('test-results',{recursive:true});
 await page.goto(f.url); await page.locator('#library-tab-own').waitFor();
 assert.equal(await page.locator('#navigation [data-id="home"],#navigation [data-id="search"]').count(),0);
 await click('open-list',list.id);
 await select(ids[0]); await select(ids[2],true);
 assert.equal(await page.locator('[data-selection-count]').textContent(),'3');
 await click('bulk-favorite');
 await page.waitForFunction(()=>document.querySelector('.selection-toolbar')?.hidden);
 assert.equal((await c.request('/library')).data.favorites.length,3);
 await select(ids[0]); await select(ids[2],true);
 await page.screenshot({path:'test-results/optimization-selection.png'});
 await click('select-page'); assert.equal(await page.locator('[data-selection-count]').textContent(),'4');
 await click('clear-selection'); await select(ids[0]); await select(ids[2],true);
 await click('bulk-delete'); await click('confirm-bulk-delete');
 await page.waitForFunction(()=>document.querySelectorAll('tr[data-track]').length===1);
 assert.deepEqual((await c.request('/library')).data.playlists.find(p=>p.id===list.id).trackIds,[ids[3]]);
 await click('navigate','favorites');
 const favoriteIds = await page.locator('tr[data-track]').evaluateAll(rows=>rows.map(r=>r.dataset.track));
 await click('favorite',favoriteIds[0]);
 await page.waitForFunction(id=>document.querySelector(`[data-action="favorite"][data-id="${id}"]`)?.getAttribute('aria-pressed')==='false',favoriteIds[0]);
 assert.equal(await page.locator('tr[data-track]').count(),3);
 await page.evaluate(()=>{window.harmonyDesktop={savePlaylistFile:async input=>{window.exported=JSON.parse(input.content);return true;}};});
 await click('export-favorites'); await page.waitForFunction(()=>window.exported);
 assert.equal(await page.evaluate(()=>window.exported.playlists.length),0);
 assert.equal(await page.evaluate(()=>window.exported.favorites.length),2);
 await page.reload(); await page.locator('#library-tab-own').waitFor();
 await click('navigate','favorites'); assert.equal(await page.locator('tr[data-track]').count(),2);
 await click('navigate','tracks'); await row(ids[0]).waitFor();
 await click('play',ids[0]); await page.waitForFunction(()=>document.querySelector('audio').currentTime>.1);
 assert.ok(await row(ids[0]).locator('.playing-equalizer').isVisible());
 const before = await page.locator('audio').evaluate(a=>a.currentTime);
 await page.locator('.sidebar .brand').click();
 assert.equal(await page.locator('audio').evaluate(a=>a.paused),false);
 assert.ok(await page.locator('audio').evaluate(a=>a.currentTime)>=before);
 await page.locator('audio').evaluate(a=>{a.currentTime=12;a.pause();});
 await page.reload(); await page.locator('#library-tab-own').waitFor();
 await page.waitForFunction(()=>Math.abs(document.querySelector('audio').currentTime-12)<.5);
 assert.equal(await page.locator('audio').evaluate(a=>a.paused),true);
 await page.locator('#queue-button').click(); assert.equal(await page.locator('#queue-panel [data-action="play-queued"]').count(),4);
 await page.locator('#queue-button').click();
 await click('settings');
 await page.locator('[data-shortcut="next"]').focus(); await page.keyboard.press('Control+Shift+Y');
 assert.equal(await page.locator('[data-shortcut="next"]').inputValue(),'Ctrl+Shift+Y');
 await page.screenshot({path:'test-results/optimization-settings.png'});
 await page.reload(); await page.locator('#library-tab-own').waitFor();
 await click('settings'); assert.equal(await page.locator('[data-shortcut="next"]').inputValue(),'Ctrl+Shift+Y');
 await click('navigate','tracks');
 const order = await page.locator('tr[data-track]').evaluateAll(rows=>rows.map(r=>r.dataset.track));
 await click('play',order.at(-1));
 let failed = new Set(order.slice(0,2));
 await page.route('**/api/tracks/*/audio',route=>failed.has(new URL(route.request().url()).pathname.split('/')[3])?route.fulfill({status:502,json:{error:'测试音频不可用'}}):route.continue());
 await click('play',order[0]);
 await page.waitForFunction(id=>document.querySelector(`tr[data-track="${id}"]`)?.classList.contains('playing-row')&&!document.querySelector('audio').paused&&document.querySelector('audio').currentTime>.1,order[2]);
 failed = new Set(ids);
 await click('play',order[0]);
 await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('本轮歌曲均无法播放')&&document.querySelector('audio').paused);
 await page.waitForTimeout(250);
 assert.equal(await page.locator('audio').evaluate(a=>a.paused),true);
 await page.unroute('**/api/tracks/*/audio');
 await click('play',ids[3]); await page.waitForFunction(()=>!document.querySelector('audio').paused);
 await page.setViewportSize({width:760,height:900});
 await select(ids[3]); assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log('PASS 批量收藏/移除、Shift 连选、取消喜欢保留行、喜欢导出、LOGO 续播、缓存恢复队列与进度、快捷键保存、失败跳曲/一轮暂停、窄窗口');
} finally { await browser.close(); await f.close(); }
