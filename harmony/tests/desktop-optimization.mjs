import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { resolve,join } from 'node:path';
import { tmpdir } from 'node:os';
import { wav } from './helpers.js';
const root=resolve(tmpdir()), userData=await mkdtemp(join(root,'harmony-optimization-'));
const env={...process.env,HARMONY_USER_DATA:userData,HARMONY_TEST_HIDDEN:'1'};delete env.ELECTRON_RUN_AS_NODE;
let app;
async function launch(){app=await electron.launch({args:['.'],env,timeout:45000});const page=await app.firstWindow();await page.waitForLoadState('domcontentloaded');return page;}
try{
 let page=await launch(); await page.locator('#guest-start').click(); await page.locator('#library-tab-own').waitFor();
 await page.locator('[data-action="navigate"][data-id="local"]').click();
 const music=join(userData,'原文件.wav');await writeFile(music,wav(40));
 await app.evaluate(({dialog},music)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[music]});},music);
 await page.locator('[data-action="import-files"]').click(); await page.locator('tr[data-track]').waitFor();
 const id=await page.locator('tr[data-track]').getAttribute('data-track');
 await page.locator('tr[data-track]').hover();await page.locator('[data-select-track]').check();
 await page.locator('[data-action="bulk-favorite"]').click();
 await page.waitForFunction(()=>document.querySelector('.selection-toolbar').hidden);
 const p=await page.evaluate(async()=>{const r=await fetch('/api/playlists',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'本地引用歌单'})});return (await r.json()).playlist;});
 await page.reload();await page.locator('#library-tab-own').waitFor();
 await page.locator('[data-action="navigate"][data-id="local"]').click();
 await page.locator('tr[data-track]').hover();await page.locator('[data-select-track]').check();
 await page.locator('[data-action="bulk-add"]').click();await page.locator(`[data-action="bulk-choose-list"][data-id="${p.id}"]`).click();
 await page.locator('#dialog').waitFor({state:'hidden'});
 await page.locator(`[data-action="open-list"][data-id="${p.id}"]`).click();
 await page.locator('[data-action="play"]').click();await page.waitForFunction(()=>document.querySelector('audio').currentTime>.1);
 await page.locator('audio').evaluate(a=>{a.currentTime=9;a.dispatchEvent(new Event('seeked'));});
 const savedId=await page.locator('tr[data-track]').getAttribute('data-track');
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getTitle().includes('桌面歌词')).close());
 assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),false);
 assert.equal(await page.locator('audio').evaluate(a=>a.paused),false);
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].show());
 await page.evaluate(()=>window.harmonyDesktop.setPreferences({closeAction:'ask'}));
 await app.evaluate(({dialog,BrowserWindow})=>{dialog.showMessageBox=async()=>({response:2});BrowserWindow.getAllWindows()[0].close();});
 assert.equal(await page.evaluate(()=>document.querySelector('audio').paused),false);
 await page.evaluate(()=>window.harmonyDesktop.setPreferences({shortcuts:{next:'Ctrl+Shift+Y'}}));
 await page.locator('audio').evaluate(a=>{a.currentTime=11;a.pause();});
 await page.waitForTimeout(200);
 await app.close();app=null;
 page=await launch();await page.locator('#library-tab-own').waitFor();
 assert.equal((await page.evaluate(()=>window.harmonyDesktop.getPreferences())).shortcuts.next,'Ctrl+Shift+Y');
 await page.locator('#play-toggle').click();await page.waitForFunction(()=>document.querySelector('audio').currentTime>=10.5&&!document.querySelector('audio').paused);
 assert.equal(await page.locator('#now-playing-info b').textContent(),'原文件');
 await page.locator('#queue-button').click();assert.equal(await page.locator('#queue-panel [data-action="play-queued"]').getAttribute('data-id'),savedId);
 await page.locator('#queue-button').click();
 await page.evaluate(()=>window.harmonyDesktop.setPreferences({closeAction:'tray'}));
 await page.locator('[data-action="navigate"][data-id="local"]').click();
 await page.locator('tr[data-track]').hover();await page.locator('[data-select-track]').check();
 await page.locator('[data-action="bulk-delete"]').click();await page.locator('[data-action="confirm-bulk-delete"]').click();
 await page.waitForFunction(()=>!document.querySelector('tr[data-track]'));
 assert.deepEqual(await page.evaluate(()=>window.harmonyDesktop.listLocalFiles()),[]);
 assert.ok((await (await import('node:fs/promises')).stat(music)).isFile());
 console.log('PASS Windows 托盘关闭继续播放、询问取消、跨进程恢复本地引用/队列/进度、本地批量收藏/加入歌单/移除索引');
}finally{await app?.close();if(!userData.startsWith(root+ '\\')||!userData.includes('harmony-optimization-'))throw Error('Unsafe cleanup');await rm(userData,{recursive:true,force:true});}
